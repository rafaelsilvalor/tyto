/**
 * The few pieces of Markdown every reference page is made of.
 *
 * The site compiles each page as a Vue template (ADR 0101), so text that came out of the code
 * goes into a code span or through `prose` — a `{{` or a line opening with `<dir>` outside code
 * breaks the build, and a `|` breaks a table row.
 */

export type Locale = 'en' | 'pt-BR';

export const LOCALES: readonly Locale[] = ['en', 'pt-BR'];

/** The first line of every page, so nobody edits one by hand and loses the edit. */
export function generatedHeader(source: string): string {
  return (
    `<!-- Generated by tools/docs-gen from ${source}. Do not edit: ` +
    'run `pnpm docs:gen` and commit the result. -->'
  );
}

/** A code span that holds any text, backticks and table pipes included. */
export function code(text: string): string {
  const fence = text.includes('`') ? '`` ' : '`';
  const closing = fence === '`` ' ? ' ``' : '`';
  return `${fence}${text.replaceAll('|', '\\|')}${closing}`;
}

/** Text from the code shown as prose: one line, no table pipes, no Vue interpolation. */
export function prose(text: string): string {
  return text
    .replace(/\s+/gu, ' ')
    .trim()
    .replaceAll('|', '\\|')
    .replaceAll('{{', '{&#8203;{')
    .replaceAll('<', '&lt;');
}

export function table(header: readonly string[], rows: readonly (readonly string[])[]): string {
  const line = (cells: readonly string[]): string => `| ${cells.join(' | ')} |`;
  return [line(header), line(header.map(() => '---')), ...rows.map(line)].join('\n');
}

/** Paragraphs and blocks joined by one blank line, ending in one newline. */
export function page(blocks: readonly string[]): string {
  return `${blocks.filter((block) => block !== '').join('\n\n')}\n`;
}
